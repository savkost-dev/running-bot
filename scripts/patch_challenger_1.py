"""Шаг 2 синхронизации: факторный блок анализа → challenger-промт рекомендации.

Работает ТОЛЬКО в теле build_evening_prompt_challenger (champion не трогает):
  - удаляет три строки жёсткой трёхступеньки (длинные/короткие/смешанные);
  - после строки "АЛГОРИТМ ВЫБОРА ГРУППЫ:" вставляет факторный блок
    (длина+повторы+объём, отдых с регламентом, непрерывные связки,
    непрерывная шкала ПАНО↔МПК с якорем 400-1000, анти-перестраховка).
Идемпотентен. Запуск: python scripts/patch_challenger_1.py
"""
P = r"D:\running-bot\src\claude_advisor.py"

with open(P, encoding="utf-8") as f:
    lines = f.readlines()

src = "".join(lines)
if "ФАКТОРЫ ИНТЕНСИВНОСТИ" in src:
    print("Патч уже применён — выходим.")
    raise SystemExit(0)

ch_start = next(i for i, l in enumerate(lines)
                if l.startswith("def build_evening_prompt_challenger("))

DROP_PREFIXES = (
    '        "- Длинные отрезки (≥1 км)',
    '        "- Короткие отрезки (200-400м)',
    '        "- Смешанная работа (длинный + короткие)',
    '        "ТИП ИНТЕРВАЛЬНОЙ РАБОТЫ влияет',
)
BLOCK = [
    '        "ФАКТОРЫ ИНТЕНСИВНОСТИ (оценивай работу по совокупности, а не по одному признаку):",\n',
    '        "- Длина отрезков, число повторов и суммарный объём: режим должен быть удержим",\n',
    '        "  на ВСЁМ объёме задания, а не на одном отрезке (6×300 и 20×300 — разные тренировки).",\n',
    '        "- Отдых и его регламент: полноценное восстановление позволяет работать заметно выше ПАНО;",\n',
    '        "  темп отдыха быстрее ~5:30/км — восстановление неполное, нагрузка серии выше;",\n',
    '        "  если темп отдыха явно задан в анонсе — используй именно его, не оценку.",\n',
    '        "- Непрерывные связки (отрезки без отдыха между ними): перепад между соседними кусками",\n',
    '        "  умеренный, базовая часть — не трусца, она бежится ближе к рабочим режимам.",\n',
    '        "- Шкала интенсивности непрерывная — от ниже ПАНО до выше МПК, промежуточные уровни",\n',
    '        "  (посередине между ПАНО и МПК) допустимы. Ориентир для калибровки: классические",\n',
    '        "  интервалы 400-1000 м с трусцовым восстановлением бегут ближе к МПК, чем к ПАНО.",\n',
    '        "- Не занижай без причины: при хорошей готовности недогруз — такая же ошибка, как",\n',
    '        "  перегруз; консервативность оправдана плохим восстановлением, большим объёмом",\n',
    '        "  или коротким/быстрым отдыхом.",\n',
]

out = lines[:ch_start]
inserted = dropped = 0
for l in lines[ch_start:]:
    if any(l.startswith(p) for p in DROP_PREFIXES):
        dropped += 1
        continue
    out.append(l)
    if l.startswith('        "АЛГОРИТМ ВЫБОРА ГРУППЫ:"'):
        out.extend(BLOCK)
        inserted += 1

if inserted != 1 or dropped != 4:
    print(f"ОШИБКА: inserted={inserted}, dropped={dropped} (ожидалось 1 и 4) — файл не тронут")
    raise SystemExit(1)

with open(P, "w", encoding="utf-8", newline="") as f:
    f.writelines(out)
print(f"OK: блок вставлен, {dropped} строк трёхступеньки убрано (только в challenger)")
