"""Синхронизация анализ → рекомендация: 3 недостающих фактора в reco-challenger.

Только в теле _reco_challenger (champion заморожен). Вставки в блок
«СВЯЗЬ ТИПА РАБОТЫ С ЗОНАМИ»:
  1-2. после "- Длительный бег: зоны marathon/easy." — факторы «повторы/объём»
       (при большом числе повторов целься в нижнюю часть зоны-ориентира)
       и «непрерывные связки» (умеренный перепад, база не трусца);
  3.   после "...а не универсально-средний." — анти-перестраховка
       (недогруз при хорошем восстановлении = ошибка).
Идемпотентен, предохранитель по счётчику. Запуск: python scripts/patch_reco_1.py
"""
P = r"D:\running-bot\src\claude_advisor.py"

with open(P, encoding="utf-8") as f:
    lines = f.readlines()

if any("Число повторов и суммарный объём" in l for l in lines):
    print("Патч уже применён — выходим.")
    raise SystemExit(0)

ch = next(i for i, l in enumerate(lines) if "def " in l and "_reco_challenger" in l)

INS_AFTER_LONGRUN = [
    '        "- Число повторов и суммарный объём: ориентир должен быть удержим на ВСЁМ задании\\n"\n',
    '        "  (6×300 и 20×300 — разные тренировки: при большом числе повторов целься в нижнюю\\n"\n',
    '        "  часть зоны-ориентира, при малом — в верхнюю).\\n"\n',
    '        "- Непрерывные связки (куски разного темпа без отдыха между ними): перепад между\\n"\n',
    '        "  соседними кусками умеренный, базовая часть — не трусца, она ближе к рабочей зоне.\\n"\n',
]
INS_AFTER_TARGET = [
    '        "Не занижай без причины: при хорошем восстановлении недогруз — такая же ошибка,\\n"\n',
    '        "как перегруз; консервативность оправдана низким восстановлением, большим объёмом\\n"\n',
    '        "или коротким/быстрым отдыхом.\\n"\n',
]

out = lines[:ch]
inserted = 0
for l in lines[ch:]:
    out.append(l)
    if l.startswith('        "- Длительный бег: зоны marathon/easy.'):
        out.extend(INS_AFTER_LONGRUN)
        inserted += 1
    elif l.startswith('        "для ДАННОГО типа работы, а не универсально-средний.'):
        out.extend(INS_AFTER_TARGET)
        inserted += 1

if inserted != 2:
    print(f"ОШИБКА: inserted={inserted} (ожидалось 2) — файл не тронут")
    raise SystemExit(1)

with open(P, "w", encoding="utf-8", newline="") as f:
    f.writelines(out)
print("OK: 3 фактора вставлены в reco-challenger (повторы/объём, связки, анти-перестраховка)")
