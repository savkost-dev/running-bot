"""Три вставки из анализа в challenger боевого промта рекомендации (B).

Работает ТОЛЬКО в теле build_ai_b_prompt_reco_challenger (champion не трогает):
  1. К строке «МПК-работа (средние отрезки 300-600м …): ориентир — зона interval.»
     добавляется учёт числа повторов и суммарного объёма (20×300 vs 6×300).
  2. После строки «ПАНО/темповая …» — новый пункт про непрерывные связки.
  3. После «Рекомендованная группа должна давать темп близкий к целевому ориентиру …
     а не универсально-средний.» — анти-перестраховка.
Идемпотентен, предохранитель по счётчикам. Запуск: python scripts/patch_reco_challenger.py
"""
P = r"D:\running-bot\src\claude_advisor.py"

with open(P, encoding="utf-8") as f:
    src = f.read()

if "недогруз — такая же ошибка" in src:
    print("Патч уже применён — выходим.")
    raise SystemExit(0)

ch = src.index("def build_ai_b_prompt_reco_challenger(")
head, tail = src[:ch], src[ch:]
n = 0

old1 = "ориентир — зона interval.\n"
new1 = ("ориентир — зона interval. Учитывай число повторов и суммарный объём:\n"
        "  серия должна быть удержима ЦЕЛИКОМ — при большом количестве повторов\n"
        "  (например 20×300) допустим ориентир между threshold и interval,\n"
        "  при малом (6-8) — уверенно interval.\n")
if old1 in tail:
    tail = tail.replace(old1, new1, 1)
    n += 1

old2 = "- ПАНО/темповая (длинные отрезки, короткий отдых): ориентир — зона threshold.\n"
new2 = (old2 +
        "- Непрерывные связки (куски разного темпа БЕЗ отдыха между ними): перепад между\n"
        "  соседними кусками умеренный, базовая часть — не трусца, она ближе к рабочей зоне.\n")
if old2 in tail:
    tail = tail.replace(old2, new2, 1)
    n += 1

old3 = "а не универсально-средний.\n"
new3 = ("а не универсально-средний.\n"
        "Не занижай без причины: при нормальном восстановлении недогруз — такая же ошибка,\n"
        "как перегруз; консервативность оправдана плохим восстановлением, большим объёмом\n"
        "или быстрым отдыхом.\n")
if old3 in tail:
    tail = tail.replace(old3, new3, 1)
    n += 1

if n != 3:
    print(f"ОШИБКА: применено {n} из 3 вставок — файл не тронут")
    raise SystemExit(1)

with open(P, "w", encoding="utf-8", newline="") as f:
    f.write(head + tail)
print("OK: 3 вставки в challenger (повторы/объём, связки, анти-перестраховка)")
