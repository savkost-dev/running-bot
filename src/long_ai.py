def mar_band(easy_s: int, mar_s: int) -> int:
    """Верхний край марафонской полосы, с/км медленнее марафонского: четверть зазора между лёгким и марафонским
    (Антон, 07.10.2026: жёсткие +15 с у быстрого бегуна съедали почти половину зазора — 4:00 при марафонском
    3:46 читалось как марафонская). У медленного зазор 60 с → +15, у быстрого 37 с → +9."""
    return max(0, int(round((easy_s - mar_s) / MAR_BAND_SHARE)))


def half_zone(pace_s: int, easy_s: int, mar_s: int, thr_s: int | None) -> str:
    """Зона половины по личным темпам (Антон, 07.10.2026): «медленно» / «лёгкая» / «переходная» /
    «марафонская» / «перебор». Границы: лёгкая +45, марафонская −OVER_EDGE и +четверть зазора (mar_band)."""
    if pace_s < mar_s - OVER_EDGE or (thr_s is not None and pace_s <= thr_s):
        return "перебор"
    if pace_s <= mar_s + mar_band(easy_s, mar_s):
        return "марафонская"
    if pace_s < easy_s:
        return "переходная"
    if pace_s <= easy_s + 45:
        return "лёгкая"
    return "медленно"


ZONE_BORDER_TOL = 7   # с/км (Антон, 07.10): ближе — половина «на границе» двух зон, в жизни темп гуляет на ±5–7 с/км


def zone_border_note(pace_s: int, easy_s: int, mar_s: int, thr_s: int | None, tol: int = ZONE_BORDER_TOL) -> str:
    """Пометка «на границе переходная/марафонская (4 с)», если темп половины ближе tol к границе зон; иначе ''.
    Антон, 07.10.2026: границы жёсткие, ИИ должен видеть пограничные случаи. Вечер 07.10: помечаются только
    границы, где меняется смысл варианта — с марафонской, с перебором и порог; границы медленно/лёгкая и
    лёгкая/переходная не помечаются (ИИ читал любую пометку как опасность и уходил на 30 с медленнее лёгкого)."""
    borders = [(mar_s + mar_band(easy_s, mar_s), "переходная/марафонская")]
    # 08.10.2026 (Антон): «у перебора» — только если половина быстрее марафонского больше чем на 10 с/км: марафонский
    # темп и до −10 — целевая работа для IV/V, не край. Раньше край стоял на −5 и при допуске 7 с любая половина ровно
    # в марафонском темпе помечалась как пограничная, ИИ читал это как риск (IV рекомендован 5 из 43, V ни разу).
    if pace_s < mar_s - 10:
        borders.append((mar_s - OVER_EDGE, "марафонская/перебор"))
        if thr_s is not None:
            borders.append((thr_s, "порог"))
    best = min(borders, key=lambda b: abs(pace_s - b[0]))
    d = abs(pace_s - best[0])
    return f"на границе {best[1]} ({d} с)" if d <= tol else ""


def _zone_spans(easy_s: int, mar_s: int) -> dict:
    """Отрезки зон в секундах темпа (медленнее — больше): для меры похожести варианта на тип."""
    top = mar_s + mar_band(easy_s, mar_s)
    big = 10 ** 6
    return {"лёгкая": (easy_s, easy_s + 45), "переходная": (top + 1, easy_s - 1),
            "марафонская": (mar_s - OVER_EDGE, top), "не быстрее лёгкой": (easy_s, big),
            "лёгкая или переходная": (top + 1, easy_s + 45)}


# Требование типа к половинам (зоны из _zone_spans) — та же таблица пар, что в промте
_TYPE_SPANS = (
    ("спокойная аэробная", "не быстрее лёгкой", "лёгкая"),
    ("аэробный прогресс", "лёгкая", "переходная"),
    ("развивающая аэробная", "переходная", "переходная"),
    ("быстрый финиш в марафонском темпе", "лёгкая или переходная", "марафонская"),
    ("ровная марафонская", "марафонская", "марафонская"),
)


def _span_dist(pace_s: int, span: tuple) -> int:
    lo, hi = span
    return 0 if lo <= pace_s <= hi else (lo - pace_s if pace_s < lo else pace_s - hi)


def type_distances(first_s: int, second_s: int, easy_s: int, mar_s: int) -> list[int]:
    """Насколько вариант не похож на каждый из пяти типов (порядок _TYPE_SPANS): сумма секунд, на которые
    половины выходят из зон типа. 0 — обе половины внутри."""
    sp = _zone_spans(easy_s, mar_s)
    return [_span_dist(first_s, sp[a]) + _span_dist(second_s, sp[b]) for _, a, b in _TYPE_SPANS]


def assign_types(ladder: list[dict], easy_s: int, mar_s: int, thr_s: int | None) -> None:
    """Зоны половин и тип каждого варианта — в сам вариант (zone1, zone2, type, dist).
    Тип (Антон, 07.10.2026, «ползущий» проход): лесенка идёт от медленного к быстрому; первый вариант не из
    «слишком медленно» — тип I, дальше на каждом шаге тип переключается на следующий (I → II → III → IV → V),
    пока следующий похож на вариант сильнее текущего (type_distances); назад не откатывается. Так у быстрого
    бегуна с узкой переходной зоной 1+ не перелетает с I на IV через непохожие II и III, и лесенка монотонна.
    «Слишком медленно» (вторая половина в «медленно») и «перебор» (любая половина) — как раньше, по зонам."""
    cur, used = None, set()
    for v in ladder:
        f, s = v["first_s"], v["second_s"]
        z1, z2 = half_zone(f, easy_s, mar_s, thr_s), half_zone(s, easy_s, mar_s, thr_s)
        v["zone1"], v["zone2"] = z1, z2
        if "перебор" in (z1, z2):
            v["type"], v["dist"] = "перебор", None
            continue
        if z2 == "медленно":
            v["type"], v["dist"] = "слишком медленно", None
            continue
        d = type_distances(f, s, easy_s, mar_s)
        if cur is None:
            cur = 0
        # следующий тип берём, если он похож сильнее; или если он почти подходит (в допуске ZONE_BORDER_TOL —
        # темп в жизни гуляет на ±7 с/км), а текущий тип уже достался предыдущему, более медленному варианту:
        # так зона уже шага лесенки (30 с) не выпадает из типов. Второй шаг подряд — только по строгой похожести.
        while cur + 1 < len(_TYPE_SPANS) and d[cur + 1] < d[cur]:
            cur += 1
        if cur + 1 < len(_TYPE_SPANS) and d[cur + 1] <= ZONE_BORDER_TOL and cur in used and d[cur + 1] >= d[cur]:
            cur += 1   # шаг по допуску — один, дальше не идём
        used.add(cur)
        v["type"], v["dist"] = _TYPE_SPANS[cur][0], d


def build_ladder(analysis: dict, zones_map: dict | None) -> tuple[list[dict], dict | None]:
    """Лесенка вариантов от медленного к быстрому из анализа анонса лонга.
    Темп группы — первый М:СС в строке work; «прогресс» — вторая половина на 30 с/км быстрее
    (шаг групп клуба). Возвращает (варианты, группа здоровья | None).
    Вариант: {label, first_s, second_s, progressive}."""
    step = 30
    rows, health = [], None
    for g in (analysis or {}).get("groups") or []:
        if g.get("health_group"):
            health = g
            continue
        m = re.search(r"\b(\d{1,2}:\d{2})\b", g.get("work") or "")
        s = _sec(m.group(1)) if m else None
        if s is None:
            continue
        num = g.get("number")
        rows.append({"label": f"гр.{num} ровно", "num": str(num), "first_s": s, "second_s": s,
                     "progressive": False})
        rows.append({"label": f"гр.{num}-прогресс", "num": str(num), "first_s": s, "second_s": s - step,
                     "progressive": True})
    # медленный → быстрый: по темпу первой половины, при равенстве ровный раньше прогресса
    rows.sort(key=lambda r: (-r["first_s"], r["progressive"]))
    return rows, health


def _runs_from_strava(activities: list[dict]) -> list[dict]:
    """Пробежки из окна Strava (detail_json): [{date, km, min, pace_s, hr, weekday}] новые сверху."""
    out = []
    for a in activities or []:
        if str(a.get("type") or a.get("sport_type") or "") not in ("Run", "TrailRun", "VirtualRun"):
            continue
        dist, mov = a.get("distance") or 0, a.get("moving_time") or 0
        d = str(a.get("start_date_local") or a.get("start_date") or "")[:10]
        if not d or dist < 500 or mov < 120:
            continue
        try:
            wd = datetime.strptime(d, "%Y-%m-%d").weekday()
        except ValueError:
            continue
        out.append({"date": d, "km": dist / 1000.0, "min": mov / 60.0,
                    "pace_s": mov / (dist / 1000.0), "hr": a.get("average_heartrate"), "weekday": wd})
    out.sort(key=lambda r: r["date"], reverse=True)
    return out


def build_long_ai_package(*, profile: dict | None, zinfo: dict | None, recovery: dict | None,
                          fitness: dict | None, analysis: dict | None, activities: list[dict] | None,
                          age: int | None = None, today: str | None = None,
                          weather_prompt: str = "", scenario_text: str = "", work_text: str = "") -> dict:
    """Пакет данных для PROMPT_LONG_AI текстом. Сырые данные собирает вызывающий (_run_long_ai).
    Возвращает {ok, text, ladder, msg}. В пакет идут только перечисленные поля профиля —
    словарь профиля целиком не печатать (в нём лежат учётные данные сервисов)."""
    prof = profile or {}
    zones_map = (zinfo or {}).get("zones") or {}
    easy_s, mar_s, thr_s = _sec(zones_map.get("easy")), _sec(zones_map.get("marathon")), _sec(zones_map.get("threshold"))
    ladder, health = build_ladder(analysis or {}, zones_map)
    if not ladder:
        return {"ok": False, "msg": "В анализе анонса лонга нет групп с темпом."}
    if easy_s is None or mar_s is None:
        return {"ok": False, "msg": "Нет личных зон (лёгкий и марафонский темп) — нужен VO2max или порог в профиле."}

    L = []
    A = L.append
    today_d = datetime.strptime(today, "%Y-%m-%d") if today else datetime.now()
    A(f"Дата расчёта: {today_d.strftime('%Y-%m-%d')}")

    # 07.10.2026 (Антон, выравнивание с интервалами): о бегуне — только специализация и зоны темпа,
    # тем же текстом, что в build_ai_b_prompt_reco_champion. Пол, возраст, МПК, ПАНО, тип бегуна
    # модели не показываются: они уже заложены в зоны.
    A("\n[БЕГУН]")
    spec = prof.get("specialization")
    A(f"  Специализация: {SPEC_LABELS.get(spec, spec or 'не указана')}")
    A("  Зоны темпа:")
    for _z, _p in zones_map.items():
        A(f"    {_z}: {_p} мин/км")

    A("\n[ФОН]")
    rec = recovery or {}
    # 07.10.2026 (Антон, выравнивание с интервалами): в промт идёт только Training Readiness с временем
    # измерения — как в claude_advisor.build_ai_b_prompt_reco_champion. HRV, сон, батарея, процент
    # восстановления модели не показываются (у интервалов они в промт не идут намеренно).
    tr = rec.get("training_readiness")
    if isinstance(tr, dict) and tr.get("score") is not None:
        tr_at_str = ""
        tr_at_raw = rec.get("training_readiness_at")
        if tr_at_raw:
            try:
                from datetime import timezone as _tz
                _dt_obj = datetime.fromisoformat(str(tr_at_raw).replace("Z", "+00:00"))
                if _dt_obj.tzinfo is None:
                    _dt_obj = _dt_obj.replace(tzinfo=_tz.utc)
                tr_at_str = f", измерен {(_dt_obj + timedelta(hours=3)).strftime('%H:%M %d.%m')}"
            except Exception:
                pass
        # 08.10.2026 (Антон): ярлык Garmin (moderate/high…) не показываем — он перетягивал 71 в «среднюю»
        # готовность; шкала непрерывная, модель смотрит на число
        A(f"  Восстановление: Training Readiness: {tr['score']}/100{tr_at_str}")
    else:
        A("  Восстановление: нет данных")
    if scenario_text:
        # сценарий времени (recovery._recovery_scenario), тот же текст, что у интервалов:
        # «данные синхронизированы …, до старта N ч, прогноз к старту» / «тренировка уже состоялась»
        A(f"  {scenario_text}")
    # 07.10.2026 (Антон): вместо «нагрузка за 48 ч» (число трен., км, средний темп — восстановительный
    # кросс выглядел как нагрузка) — таблица объёма за 7 дней по часам бегуна с ярлыками работы и абзацем
    # «Как учитывать» под длительную (claude_advisor._work_prompt_text(kind="long")); собирает вызывающий.
    if work_text:
        for _ln in work_text.rstrip("\n").split("\n"):
            A("  " + _ln)
    else:
        A("  Нагрузка за 7 дней: нет данных")
    # Сводка нагрузки и TSB — как в прежнем ИИ-промте лонга (есть не у всех источников)
    load = (fitness or {}).get("training_load") or {}
    if load.get("summary"):
        A(f"  Нагрузка (сводка): {load['summary']}")
    if load.get("tsb") is not None:
        A(f"  TSB: {load['tsb']} ({'накопленная усталость' if load['tsb'] <= -15 else 'усталости нет'})")
    race = (fitness or {}).get("last_race") or {}
    if race.get("date"):
        A(f"  Последний старт: {race['date']}, {race.get('distance_km', '?')} км, "
          f"{race.get('days_since', '?')} дн. назад"
          + (f" — ещё восстанавливается, до {race.get('recovery_until')}" if race.get("still_recovering") else ""))

    runs = _runs_from_strava(activities or [])
    A(f"\n[ОБЪЁМ] (бег по неделям, последние {HISTORY_WEEKS} недель, пн–вс)")
    if runs:
        monday = (today_d - timedelta(days=today_d.weekday())).date()
        for w in range(HISTORY_WEEKS):
            ws, we = monday - timedelta(weeks=w), monday - timedelta(weeks=w) + timedelta(days=6)
            wk = [r for r in runs if ws.isoformat() <= r["date"] <= we.isoformat()]
            A(f"  {ws.strftime('%d.%m')}–{we.strftime('%d.%m')}: {sum(r['km'] for r in wk):.0f} км, "
              f"{len(wk)} пробежек" + (" (текущая, неполная)" if w == 0 else ""))
    else:
        A("  нет данных (нет окна тренировок Strava)")

    A(f"\n[ИСТОРИЯ] (пробежки от {LONG_MIN_MINUTES} мин за {HISTORY_WEEKS} недель; "
      f"расстояния до личных темпов, с/км: + медленнее, − быстрее)")
    since = (today_d - timedelta(weeks=HISTORY_WEEKS)).strftime("%Y-%m-%d")
    longs = [r for r in runs if r["min"] >= LONG_MIN_MINUTES and r["date"] >= since]
    if longs:
        wd_names = ["пн", "вт", "ср", "чт", "пт", "сб", "вс"]
        for r in longs:
            ps = int(round(r["pace_s"]))
            A(f"  {r['date']} ({wd_names[r['weekday']]}): {r['km']:.1f} км, {r['min']:.0f} мин, "
              f"ср. темп {_fmt(ps)} (к лёгкому {_gap(ps, easy_s)}, к марафонскому {_gap(ps, mar_s)})"
              + (f", пульс {round(r['hr'])}" if r.get("hr") else ""))
        A("  Средний темп сглаживает прогресс: длительная с ускорением во второй половине выглядит ровной.")
    elif runs:
        A("  длительных нет")
    else:
        A("  нет данных")

    A("\n[АНОНС]")
    an = analysis or {}
    if an.get("workout_date"):
        A(f"  Дата длительной: {an['workout_date']}")
    if an.get("summary"):
        A(f"  Суть: {an['summary']}")

    if weather_prompt:
        A("\n[ПОГОДА] (на время длительной)")
        for ln in str(weather_prompt).strip().split("\n"):
            A(f"  {ln.strip()}")

    A("\n[ВАРИАНТЫ] (лесенка от медленного к быстрому; для каждой половины — зона по личным темпам и "
      "расстояние до них, с/км: + медленнее, − быстрее; тип — по проходу лесенки)")
    _roman_of = {k: v for k, v in LONG_TYPE_ROMAN.items()}
    assign_types(ladder, easy_s, mar_s, thr_s)   # 07.10.2026 (Антон): тип — «ползущим» проходом, не таблицей пар
    for v in ladder:
        f, s = v["first_s"], v["second_s"]
        z1, z2, t = v["zone1"], v["zone2"], v["type"]
        t_disp = f"{_roman_of[t]} {t}" if t in _roman_of else t
        b1, b2 = zone_border_note(f, easy_s, mar_s, thr_s), zone_border_note(s, easy_s, mar_s, thr_s)
        if v["progressive"]:
            border = " | ".join(x for x in ((f"1-я {b1}" if b1 else ""), (f"2-я {b2}" if b2 else "")) if x)
            A(f"  {v['label']}: {_fmt(f)} → {_fmt(s)} | зоны: {z1} → {z2} | тип: {t_disp}"
              + (f" | {border}" if border else "") + " | "
              f"1-я половина: к лёгкому {_gap(f, easy_s)}, к марафонскому {_gap(f, mar_s)}, к порогу {_gap(f, thr_s)} | "
              f"2-я половина: к лёгкому {_gap(s, easy_s)}, к марафонскому {_gap(s, mar_s)}, к порогу {_gap(s, thr_s)}")
        else:
            A(f"  {v['label']}: {_fmt(f)} все 100 мин | зона: {z1} | тип: {t_disp}"
              + (f" | {b1}" if b1 else "") + " | "
              f"к лёгкому {_gap(f, easy_s)}, к марафонскому {_gap(f, mar_s)}, к порогу {_gap(f, thr_s)}")
    if health:
        A(f"  группа здоровья (гр.{health.get('number')}): {health.get('work') or 'бег с ходьбой'}")

    return {"ok": True, "text": "\n".join(L), "ladder": ladder}


def format_extras(advice: dict) -> str:
    """Тестовый хвост к сообщению: поля, которых нет в боевом виде рекомендации лонга
    (format_long_run_message их не показывает) — тип, марафонская работа, граница перебора, разбор вариантов."""
    adv = advice or {}
    out = []
    if adv.get("long_type"):
        out.append(f"🏷 Тип длительной: {adv['long_type']}")
    if adv.get("marathon_block"):
        out.append(f"🏁 Марафонская работа\n{adv['marathon_block']}")
    if adv.get("overdo_from"):
        out.append(f"⛔ Перебор\n{adv['overdo_from']}")
    rows = [r for r in (adv.get("variants_review") or []) if isinstance(r, dict)]
    if rows:
        out.append("🧩 Разбор вариантов (служебное)\n" + "\n".join(
            f"{'✅' if r.get('ok') else '✖️'} {r.get('variant', '?')} — {r.get('type', '?')}"
            + (f": {r['why']}" if r.get("why") else "") for r in rows))
    return "\n\n".join(out)
