def _sec(pace) -> int | None:
    """'5:30' → 330; None, если не темп."""
    m = re.fullmatch(r"\s*(\d{1,2}):(\d{2})\s*", str(pace or ""))
    return int(m.group(1)) * 60 + int(m.group(2)) if m else None


def _fmt(sec) -> str:
    sec = int(round(sec))
    return f"{sec // 60}:{sec % 60:02d}"


def _gap(pace_s: int, ref_s: int | None) -> str:
    """Расстояние до личного темпа: '+20' — медленнее на 20 с/км, '−5' — быстрее."""
    if ref_s is None:
        return "—"
    d = pace_s - ref_s
    return f"+{d}" if d > 0 else (f"−{-d}" if d < 0 else "0")


def build_ladder(analysis: dict, zones_map: dict | None) -> tuple[list[dict], dict | None]:
    """Лесенка вариантов от медленного к быстрому из анализа анонса лонга.
    Темп группы — первый М:СС в строке work; «прогресс» — вторая половина на 30 с/км быстрее
    (шаг групп клуба). Возвращает (варианты, группа здоровья | None).
    Вариант: {label, first_s, second_s, progressive}."""
    step = 30
    rows, health = [], None
    for g in (analysis or {}).get("groups") or []:
        if g.get("health_group"):
            health = g
            continue
        m = re.search(r"\b(\d{1,2}:\d{2})\b", g.get("work") or "")
        s = _sec(m.group(1)) if m else None
        if s is None:
            continue
        num = g.get("number")
        rows.append({"label": f"гр.{num} ровно", "num": str(num), "first_s": s, "second_s": s,
                     "progressive": False})
        rows.append({"label": f"гр.{num}-прогресс", "num": str(num), "first_s": s, "second_s": s - step,
                     "progressive": True})
    # медленный → быстрый: по темпу первой половины, при равенстве ровный раньше прогресса
    rows.sort(key=lambda r: (-r["first_s"], r["progressive"]))
    return rows, health


def _runs_from_strava(activities: list[dict]) -> list[dict]:
    """Пробежки из окна Strava (detail_json): [{date, km, min, pace_s, hr, weekday}] новые сверху."""
    out = []
    for a in activities or []:
        if str(a.get("type") or a.get("sport_type") or "") not in ("Run", "TrailRun", "VirtualRun"):
            continue
        dist, mov = a.get("distance") or 0, a.get("moving_time") or 0
        d = str(a.get("start_date_local") or a.get("start_date") or "")[:10]
        if not d or dist < 500 or mov < 120:
            continue
        try:
            wd = datetime.strptime(d, "%Y-%m-%d").weekday()
        except ValueError:
            continue
        out.append({"date": d, "km": dist / 1000.0, "min": mov / 60.0,
                    "pace_s": mov / (dist / 1000.0), "hr": a.get("average_heartrate"), "weekday": wd})
    out.sort(key=lambda r: r["date"], reverse=True)
    return out


